"""systemd integration: the door units, their state, logs, and restarts that never kill a turn by surprise.

A restart kills every running turn of a door, including the turn that asked for it, before its answer is
delivered. So:
  * `--when-idle` waits until no turn is running (run markers in state/running/, see core.running);
  * a restart requested from inside a turn (ARCHI_CONVERSATION is set) is never done in place: it is
    handed to a transient systemd unit (systemd-run), outside the door's cgroup, which waits until the
    turn has delivered its answer and the door is idle, then restarts. Without systemd-run a detached
    sleeper does the same.
"""
from __future__ import annotations

import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

from core import running
from core.config import CODE_DIR, Config

DOORS = {"telegram": "Telegram", "matrix": "Matrix"}      # door name -> title
UNIT_DIR = Path(os.environ.get("ARCHI_UNIT_DIR", "/etc/systemd/system"))
SYSTEMD_UNIT_DIRS = ("/etc/systemd/system", "/run/systemd/system", "/usr/local/lib/systemd/system",
                     "/usr/lib/systemd/system", "/lib/systemd/system")
IN_TURN_MIN_DELAY_S = 3

UNIT_TEMPLATE = """\
# Generated by `archi service install`; edits are overwritten on the next install.
[Unit]
Description=Archi agent: {title} door
Documentation=https://github.com/Evenorchik/archi
After=network-online.target
Wants=network-online.target
StartLimitIntervalSec=0

[Service]
Type=simple
User=root
WorkingDirectory={home}
Environment=ARCHI_HOME={home}
Environment=HOME={user_home}
Environment=PATH={path}
Environment=PYTHONUNBUFFERED=1
ExecStart={python} -m doors.{door}
Restart=always
RestartSec=5
# SIGTERM to the door only: it stops its turns (killing their process trees) and exits; whatever is
# left in the cgroup gets SIGKILL.
KillSignal=SIGTERM
KillMode=mixed
TimeoutStopSec=30

[Install]
WantedBy=multi-user.target
"""


def unit_name(door: str) -> str:
    return f"archi-{door}.service"


def venv_python(code_dir: Path = CODE_DIR) -> str:
    p = Path(code_dir) / ".venv" / "bin" / "python"
    return str(p) if p.exists() else sys.executable


def unit_text(door: str = "telegram", home: Path | str | None = None, *, python: str | None = None,
              user_home: str | None = None) -> str:
    home = str(Path(home or Config().home))
    user_home = user_home or os.path.expanduser("~root") or "/root"
    path = ":".join([f"{user_home}/.local/bin", "/usr/local/sbin", "/usr/local/bin", "/usr/sbin", "/usr/bin",
                     "/sbin", "/bin"])
    return UNIT_TEMPLATE.format(title=DOORS.get(door, door.title()), home=home, user_home=user_home, path=path,
                                python=python or venv_python(), door=door)


# ------------------------------------------------------------------------------------------- systemctl

def have_systemd() -> bool:
    return Path("/run/systemd/system").is_dir() and shutil.which("systemctl") is not None


def systemd_usable() -> bool:
    """systemd runs here AND reads units from UNIT_DIR. With ARCHI_UNIT_DIR pointing anywhere else (tests, a
    staging copy) unit files are written there, but systemctl is never asked to load, start or restart them:
    it would act on the host's units of the same name instead."""
    if not have_systemd():
        return False
    try:
        unit_dir = UNIT_DIR.resolve()
    except OSError:
        return False
    return any(unit_dir == Path(d).resolve() for d in SYSTEMD_UNIT_DIRS)


def configured_doors(cfg: Config | None = None) -> list[str]:
    """Doors with credentials in the config: Telegram always (the primary door), Matrix once it is set up."""
    cfg = cfg or Config()
    return ["telegram"] + (["matrix"] if cfg.get("MATRIX_ACCESS_TOKEN") else [])


def systemctl(*args: str, timeout: float = 60, check: bool = False) -> subprocess.CompletedProcess:
    return subprocess.run(["systemctl", *args], capture_output=True, text=True, timeout=timeout, check=check)


def installed_doors() -> list[str]:
    return [d for d in DOORS if (UNIT_DIR / unit_name(d)).exists()]


def unit_state(door: str) -> dict:
    """ActiveState, SubState, MainPID, NRestarts, ActiveEnterTimestamp of a door unit ({} without systemd)."""
    if not have_systemd():
        return {}
    props = "LoadState,ActiveState,SubState,MainPID,NRestarts,ActiveEnterTimestamp,UnitFileState"
    try:
        out = systemctl("show", unit_name(door), "-p", props, timeout=15).stdout
    except (OSError, subprocess.TimeoutExpired):
        return {}
    return dict(line.split("=", 1) for line in out.splitlines() if "=" in line)


def install_unit(door: str = "telegram", *, start: bool = True, home: Path | str | None = None) -> int:
    """Write the unit, enable it, and (re)start the door. Returns 0 when the door is running."""
    if not have_systemd():
        print("systemd is not running on this machine; start the door by hand: "
              f"ARCHI_HOME={home or Config().home} {venv_python()} -m doors.{door}", file=sys.stderr)
        return 1
    path = UNIT_DIR / unit_name(door)
    text = unit_text(door, home)
    changed = not path.exists() or path.read_text() != text
    if not systemd_usable():
        UNIT_DIR.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        path.chmod(0o644)
        print(f"{unit_name(door)}: written to {UNIT_DIR}, which systemd does not read (ARCHI_UNIT_DIR), so it was "
              f"not started; run the door by hand: ARCHI_HOME={home or Config().home} {venv_python()} -m "
              f"doors.{door}")
        return 0
    if changed:
        path.write_text(text)
        path.chmod(0o644)
        systemctl("daemon-reload")
    systemctl("enable", unit_name(door), "--quiet")
    if not start:
        print(f"{unit_name(door)}: installed{' (updated)' if changed else ''}, enabled")
        return 0
    was_active = unit_state(door).get("ActiveState") == "active"
    if was_active:
        # A restart kills every running turn of the door. Same policy as `archi restart`: from inside a turn
        # it is handed to a transient unit that waits until the door is idle (this turn included); otherwise
        # it waits for idle a while and, when turns are still busy, leaves the restart for later.
        what = "updated and running" if changed else "running"
        if in_turn():
            print(f"{unit_name(door)}: {what}; the restart waits until no turn is running")
            return detach_restart(delay=IN_TURN_MIN_DELAY_S, max_wait=None, home=Path(home or Config().home))
        if not wait_idle(home, max_wait=120, out=print):
            print(f"{unit_name(door)}: {what}; turns are busy, so it was not restarted"
                  + (" and still runs the old unit" if changed else "") + " (later: archi restart --when-idle)")
            return 0
    res = systemctl("restart" if was_active else "start", unit_name(door))
    if res.returncode != 0:
        print(f"{unit_name(door)}: start failed: {res.stderr.strip()}", file=sys.stderr)
        return 1
    return 0 if wait_active(door) else 1


def wait_active(door: str, timeout: float = 15) -> bool:
    """True when the unit is active and stays up for a moment (a door that crashes on start flaps)."""
    end = time.time() + timeout
    stable_since = None
    while time.time() < end:
        st = unit_state(door)
        if st.get("ActiveState") == "active" and st.get("SubState") == "running":
            stable_since = stable_since or time.time()
            if time.time() - stable_since >= 3:
                return True
        else:
            stable_since = None
        time.sleep(0.5)
    st = unit_state(door)
    print(f"{unit_name(door)} is {st.get('ActiveState', '?')} ({st.get('SubState', '?')}); "
          "see `archi logs`", file=sys.stderr)
    return False


# ------------------------------------------------------------------------------------------- restart

def in_turn() -> bool:
    """True when this process runs inside an agent turn (the door sets ARCHI_CONVERSATION for every turn)."""
    return bool(os.environ.get("ARCHI_CONVERSATION"))


def wait_idle(home: Path | str | None = None, *, max_wait: float | None = None, poll: float = 2.0,
              out=print, clock=time.monotonic, sleep=time.sleep) -> bool:
    """Block until no turn runs (True) or max_wait passed (False). Prints a short progress line now and
    then. Markers past their deadline do not count, so a stuck turn delays a restart by at most its
    hard limit."""
    t0 = clock()
    last_note = None
    while True:
        busy = running.active(home)
        if not busy:
            return True
        waited = clock() - t0
        if max_wait is not None and waited >= max_wait:
            return False
        if last_note is None or clock() - last_note >= 30:
            names = ", ".join(f"{m['key']} ({int(m['age'] // 60)} min)" for m in busy[:3])
            more = f" and {len(busy) - 3} more" if len(busy) > 3 else ""
            out(f"waiting for {len(busy)} running turn(s) to finish: {names}{more}")
            last_note = clock()
        sleep(poll)


def restart_now(doors: list[str]) -> int:
    units = [unit_name(d) for d in doors]
    res = systemctl("restart", *units, timeout=120)
    if res.returncode != 0:
        print(f"restart failed: {res.stderr.strip()}", file=sys.stderr)
        return 1
    ok = all(wait_active(d) for d in doors)
    print(("restarted: " if ok else "restarted, but not healthy: ") + ", ".join(units))
    return 0 if ok else 1


def detach_restart(*, delay: float, max_wait: float | None, home: Path | str) -> int:
    """Hand the restart to a process outside this turn and outside the door's cgroup, then return at once,
    so the turn can finish and deliver its answer before anything is killed."""
    argv = [sys.executable, str(CODE_DIR / "archi"), "restart", "--when-idle", "--delay", str(int(delay))]
    if max_wait is not None:
        argv += ["--max-wait", str(int(max_wait))]
    env_home = str(home)
    if shutil.which("systemd-run") and have_systemd():
        unit = f"archi-restart-{int(time.time())}"
        cmd = ["systemd-run", "--unit", unit, "--collect", "--quiet", "--description", "Archi: restart when idle",
               "--setenv", f"ARCHI_HOME={env_home}", "--setenv", f"PATH={os.environ.get('PATH', '')}", *argv]
        res = subprocess.run(cmd, capture_output=True, text=True, timeout=30)
        if res.returncode == 0:
            print(f"restart scheduled ({unit}): it waits until no turn is running, this one included, so your "
                  "answer is delivered first. Check it afterwards with `archi status` / `archi logs`.")
            return 0
        print(f"systemd-run failed ({res.stderr.strip()}); using a detached process", file=sys.stderr)
    log = Path(env_home) / "logs" / "restart.log"
    log.parent.mkdir(parents=True, exist_ok=True)
    env = {k: v for k, v in os.environ.items() if not k.startswith("ARCHI_")}
    env["ARCHI_HOME"] = env_home
    with open(log, "a") as fh:
        subprocess.Popen(argv, stdin=subprocess.DEVNULL, stdout=fh, stderr=subprocess.STDOUT, env=env,
                         start_new_session=True, close_fds=True)
    print(f"restart scheduled (detached, log: {log}): it waits until no turn is running, this one included.")
    return 0


def restart(*, when_idle: bool = False, delay: float = 0, max_wait: float | None = None,
            home: Path | str | None = None) -> int:
    home = Path(home or Config().home)
    if not have_systemd():
        print("systemd is not running here; restart the door process yourself", file=sys.stderr)
        return 1
    if not systemd_usable():
        print(f"the door units in {UNIT_DIR} (ARCHI_UNIT_DIR) are not systemd's; restart the door processes "
              "yourself", file=sys.stderr)
        return 1
    doors = installed_doors()
    if not doors:
        print("no Archi services are installed (run `archi service install`)", file=sys.stderr)
        return 1
    if in_turn():
        # In place this would kill the very turn that asked, before its answer is sent.
        return detach_restart(delay=max(delay, IN_TURN_MIN_DELAY_S), max_wait=max_wait, home=home)
    if delay > 0:
        print(f"restarting in {int(delay)} s…", flush=True)
        time.sleep(delay)
    if when_idle and not wait_idle(home, max_wait=max_wait, out=lambda s: print(s, flush=True)):
        print(f"still busy after {int(max_wait or 0)} s; not restarting", file=sys.stderr)
        return 3
    return restart_now(doors)


# ------------------------------------------------------------------------------------------- logs

def logs(lines: int = 100, door: str | None = None) -> int:
    if not shutil.which("journalctl"):
        print("journalctl is not available", file=sys.stderr)
        return 1
    units = [unit_name(door)] if door else ["archi-*"]
    cmd = ["journalctl", "--no-pager", "-o", "short-iso", "-n", str(max(1, lines))]
    for u in units:
        cmd += ["-u", u]
    try:
        return subprocess.run(cmd, timeout=60).returncode
    except subprocess.TimeoutExpired:
        print("journalctl timed out", file=sys.stderr)
        return 1

