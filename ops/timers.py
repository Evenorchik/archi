"""systemd timers of Archi: the weekly memory curator of the self-learning loop (tools/learn/curator.py).

`archi learn enable` writes archi-learn-curator.service and archi-learn-curator.timer into the unit directory
(ARCHI_UNIT_DIR, default /etc/systemd/system) and enables the timer; `archi learn disable` stops it and
removes both files. systemctl is called only when that directory is one systemd actually reads, so pointing
ARCHI_UNIT_DIR somewhere else (tests) writes the files and touches nothing on the host.
"""
from __future__ import annotations

import os
import subprocess
from pathlib import Path

from core.config import CODE_DIR, Config

from . import service

CURATOR = "archi-learn-curator"
CALENDAR = "Mon *-*-* 05:00:00"
SYSTEM_UNIT_DIRS = ("/etc/systemd/system", "/run/systemd/system", "/usr/local/lib/systemd/system",
                    "/usr/lib/systemd/system", "/lib/systemd/system")

SERVICE_TEMPLATE = """\
# Generated by `archi learn enable`; `archi learn disable` removes it.
[Unit]
Description=Archi: weekly memory curator (self-learning loop)
Documentation=https://github.com/Evenorchik/archi
After=network-online.target
Wants=network-online.target

[Service]
Type=oneshot
User=root
WorkingDirectory={home}
Environment=ARCHI_HOME={home}
Environment=HOME={user_home}
Environment=PATH={path}
Environment=PYTHONUNBUFFERED=1
Nice=10
ExecStart={python} {code}/tools/learn/curator.py --home {home}
TimeoutStartSec=2h
"""

TIMER_TEMPLATE = """\
# Generated by `archi learn enable`; `archi learn disable` removes it.
[Unit]
Description=Archi: weekly memory curator

[Timer]
OnCalendar={calendar}
Persistent=true
RandomizedDelaySec=30min
Unit={name}.service

[Install]
WantedBy=timers.target
"""


def unit_dir() -> Path:
    return Path(os.environ.get("ARCHI_UNIT_DIR") or service.UNIT_DIR)


def systemd_managed(d: Path | None = None) -> bool:
    """True when `d` is a directory systemd loads units from (and systemd runs here)."""
    d = Path(d or unit_dir())
    try:
        real = str(d.resolve())
    except OSError:
        return False
    return real in SYSTEM_UNIT_DIRS and service.have_systemd()


def curator_units(home: Path | str | None = None, *, python: str | None = None, user_home: str | None = None,
                  calendar: str = CALENDAR, code_dir: Path = CODE_DIR) -> dict[str, str]:
    home = str(Path(home or Config().home))
    user_home = user_home or os.path.expanduser("~root") or "/root"
    path = ":".join([f"{user_home}/.local/bin", "/usr/local/sbin", "/usr/local/bin", "/usr/sbin", "/usr/bin",
                     "/sbin", "/bin"])
    return {
        f"{CURATOR}.service": SERVICE_TEMPLATE.format(home=home, user_home=user_home, path=path,
                                                      python=python or service.venv_python(code_dir),
                                                      code=str(code_dir)),
        f"{CURATOR}.timer": TIMER_TEMPLATE.format(calendar=calendar, name=CURATOR),
    }


def install_curator(home: Path | str | None = None, *, out=print) -> int:
    d = unit_dir()
    managed = systemd_managed(d)
    try:
        d.mkdir(parents=True, exist_ok=True)
        changed = False
        for name, text in curator_units(home).items():
            path = d / name
            if not path.exists() or path.read_text() != text:
                path.write_text(text)
                path.chmod(0o644)
                changed = True
    except OSError as e:
        out(f"weekly curator: could not write the units to {d}: {e}")
        return 1
    if not managed:
        out(f"weekly curator: units written to {d}; systemctl not called (not a systemd unit directory, or no "
            "systemd here)")
        return 0
    try:
        if changed:
            service.systemctl("daemon-reload")
        res = service.systemctl("enable", "--now", f"{CURATOR}.timer")
    except (OSError, subprocess.TimeoutExpired) as e:
        out(f"weekly curator: systemctl failed: {e}")
        return 1
    if res.returncode != 0:
        out(f"weekly curator: enabling {CURATOR}.timer failed: {res.stderr.strip()}")
        return 1
    out(f"weekly curator: {CURATOR}.timer enabled ({CALENDAR}, local time; the first run is a dry run)")
    return 0


def remove_curator(*, out=print) -> int:
    d = unit_dir()
    managed = systemd_managed(d)
    if managed:
        try:
            service.systemctl("disable", "--now", f"{CURATOR}.timer")
        except (OSError, subprocess.TimeoutExpired) as e:
            out(f"weekly curator: systemctl failed: {e}")
    removed = []
    for name in (f"{CURATOR}.timer", f"{CURATOR}.service"):
        path = d / name
        if path.exists():
            path.unlink()
            removed.append(name)
    if managed and removed:
        try:
            service.systemctl("daemon-reload")
        except (OSError, subprocess.TimeoutExpired):
            pass
    out("weekly curator: " + (f"removed {', '.join(removed)}" if removed else "was not installed"))
    return 0


def curator_state() -> dict:
    """installed (unit files present), and with systemd: ActiveState, next and last trigger."""
    d = unit_dir()
    state = {"installed": (d / f"{CURATOR}.timer").exists(), "unit_dir": str(d)}
    if state["installed"] and systemd_managed(d):
        try:
            res = service.systemctl("show", f"{CURATOR}.timer", "-p",
                                    "ActiveState,NextElapseUSecRealtime,LastTriggerUSec", timeout=15)
            state.update(dict(line.split("=", 1) for line in res.stdout.splitlines() if "=" in line))
        except (OSError, subprocess.TimeoutExpired):
            pass
    return state
